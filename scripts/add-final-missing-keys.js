const LANGS = ['en', 'hi', 'bn', 'ta', 'te', 'mr', 'gu', 'kn', 'ml', 'pa', 'ur'];

function parseDictionary(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  const dict = {};
  const regex = /^\s*([a-zA-Z0-9_]+):\s*(?:'([^']*(?:\\'[^']*)*)'|"([^"]*(?:\\"|[^"])*)"),?$/gm;
  let match;
  while ((match = regex.exec(content)) !== null) {
    const key = match[1];
    const val = match[2] !== undefined ? match[2].replace(/\\'/g, "'") : match[3].replace(/\\"/g, '"');
    dict[key] = val;
  }
  return dict;
}

// 1. Read current English dictionary
const enDict = parseDictionary('src/lib/translations/en.ts');

// Merge new keys into enDict
for (const [k, v] of Object.entries(FINAL_112_KEYS)) {
  enDict[k] = v.en;
}

const allKeys = Object.keys(enDict).sort();
console.log('Total keys now:', allKeys.length);

// 2. Generate updated interface in en.ts
const interfaceLines = allKeys.map(k => `  ${k}: string;`).join('\n');
const enValues = allKeys.map(k => `  ${k}: ${JSON.stringify(enDict[k])},`).join('\n');

const enFileContent = `export interface Translations {
${interfaceLines}
}

export const en: Translations = {
${enValues}
};
`;

fs.writeFileSync('src/lib/translations/en.ts', enFileContent, 'utf8');
console.log('Updated src/lib/translations/en.ts with', allKeys.length, 'keys');

// 3. Update all other 10 language files
LANGS.filter(l => l !== 'en').forEach(lang => {
  const filePath = `src/lib/translations/${lang}.ts`;
  const existing = parseDictionary(filePath);
  
  const values = allKeys.map(k => {
    let val = existing[k];
    if (!val) {
      if (FINAL_112_KEYS[k] && FINAL_112_KEYS[k][lang]) {
        val = FINAL_112_KEYS[k][lang];
      } else {
        val = enDict[k];
      }
    }
    return `  ${k}: ${JSON.stringify(val)},`;
  }).join('\n');

  const fileContent = `import { Translations } from './en';

export const ${lang}: Translations = {
${values}
};
`;
  fs.writeFileSync(filePath, fileContent, 'utf8');
  console.log(`Updated ${filePath} with ${allKeys.length} keys`);
});
