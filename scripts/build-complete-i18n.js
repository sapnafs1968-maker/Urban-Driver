const LANGUAGES = ['en', 'hi', 'bn', 'ta', 'te', 'mr', 'gu', 'kn', 'ml', 'pa', 'ur'];

function parseExistingFile(filePath) {
  const content = fs.readFileSync(filePath, 'utf8');
  // Extract key-value pairs from object literal
  const objMatch = content.match(/export const \w+: Translations = \{([\s\S]*?)\};/);
  if (!objMatch) return {};
  
  const dict = {};
  const lines = objMatch[1].split('\n');
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('//')) continue;
    const match = trimmed.match(/^([a-zA-Z0-9]+)\s*:\s*(['"`])([\s\S]*?)\2\s*,?$/);
    if (match) {
      dict[match[1]] = match[3];
    }
  }
  return dict;
}

// 1. Load English existing dictionary to preserve all existing keys
const enExisting = parseExistingFile(path.join(__dirname, '../src/lib/translations/en.ts'));
console.log('Existing EN keys:', Object.keys(enExisting).length);

// Extract all keys that will be in the updated Translations interface
const allKeys = Array.from(new Set([...Object.keys(enExisting), ...Object.keys(NEW_KEYS)]));
console.log('Total merged keys in updated schema:', allKeys.length);

// 2. Generate updated interface in en.ts
const interfaceLines = allKeys.map(k => `  ${k}: string;`).join('\n');

for (const lang of LANGUAGES) {
  const filePath = path.join(__dirname, `../src/lib/translations/${lang}.ts`);
  const existing = parseExistingFile(filePath);
  
  const merged = {};
  for (const key of allKeys) {
    if (NEW_KEYS[key] && NEW_KEYS[key][lang]) {
      merged[key] = NEW_KEYS[key][lang];
    } else if (existing[key]) {
      merged[key] = existing[key];
    } else if (NEW_KEYS[key] && NEW_KEYS[key]['en']) {
      merged[key] = NEW_KEYS[key]['en'];
    } else if (enExisting[key]) {
      merged[key] = enExisting[key];
    } else {
      merged[key] = key;
    }
  }

  let fileContent = '';
  if (lang === 'en') {
    fileContent = `export interface Translations {
${interfaceLines}
}

export const en: Translations = {
${allKeys.map(k => `  ${k}: ${JSON.stringify(merged[k])},`).join('\n')}
};
`;
  } else {
    fileContent = `import { Translations } from './en';

export const ${lang}: Translations = {
${allKeys.map(k => `  ${k}: ${JSON.stringify(merged[k])},`).join('\n')}
};
`;
  }

  fs.writeFileSync(filePath, fileContent, 'utf8');
  console.log(`Updated ${lang}.ts with ${allKeys.length} keys`);
}

